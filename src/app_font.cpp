void emitText(OverlayVertex* out, uint32_t& used, const char* text, float x, float y,
              float px, float py, float scale, float r, float g, float b) {
    for (int ch = 0; text[ch]; ch++) {
        const uint8_t* rows = glyph(text[ch]);
        if (!rows) continue;
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++) {
                if (!(rows[row] & (0x10 >> col)) || used >= MAX_VERTS) continue;
                out[used++] = {x + (ch * 6 + col) * scale * px, y + row * scale * py, r, g, b};
            }
    }
}
